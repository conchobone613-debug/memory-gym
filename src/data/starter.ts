/* ─────────── 불러오기 ─────────── */

const toRows = (rows: StarterRow[]) =>
  rows.map(([key, name, aliases, note]) => ({
    key,
    name,
    aliases: aliases ? aliases.split('|').filter(Boolean) : [],
    note,
    tags: ['추천'],
  }));

export function starterFor(set: ImageSet): StarterRow[] {
  if (set.domain === 'digit2') return STARTER_DIGITS;
  if (set.domain === 'cardFace') return STARTER_FACES;
  return [];
}

/**
 * 비어 있는 키에만 추천 이미지를 넣는다. 회장이 직접 채운 칸은 절대 덮지 않는다.
 * 덮어쓰려면 overwrite 를 켠다.
 */
export async function loadStarter(overwrite = false): Promise<{ filled: number; kept: number }> {
  const sets = await db.imageSets.toArray();
  let filled = 0;
  let kept = 0;
  for (const set of sets) {
    const rows = starterFor(set);
    if (rows.length === 0) continue;
    const existing = await db.images.where('setId').equals(set.id).toArray();
    const named = new Set(existing.filter((i) => i.name.trim()).map((i) => i.key));
    const target = overwrite ? toRows(rows) : toRows(rows).filter((r) => !named.has(r.key));
    kept += toRows(rows).length - target.length;
    if (target.length) {
      const r = await importRows(set.id, target);
      filled += r.updated + r.created;
    }
  }
  return { filled, kept };
}
